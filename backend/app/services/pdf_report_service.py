    def _resolve_image_on_disk(self, rel_path: Optional[str]) -> Optional[Path]:
        """Safely locate an image asset on local storage without exposing internal paths."""
        if not rel_path:
            return None
        clean = rel_path.strip().replace("\\", "/").lstrip("/")
        
        candidates = [
            settings.BASE_DIR / clean,
            settings.upload_absolute_dir / clean,
            settings.upload_absolute_dir / clean.replace("uploads/", ""),
            settings.upload_absolute_dir / "images" / Path(clean).name,
            settings.upload_absolute_dir / "processed" / Path(clean).name
        ]
        for c in candidates:
            if c.exists() and c.is_file():
                return c
        return None

    def _create_report_image(self, img_path: Optional[Path], max_width: float = 4.8 * inch, max_height: float = 2.8 * inch) -> Optional[RLImage]:
        """Load and resize inspection preview image maintaining aspect ratio."""
        if not img_path or not img_path.exists():
            return None
        try:
            with PILImage.open(img_path) as pil_img:
                w, h = pil_img.size
                if w <= 0 or h <= 0:
                    return None
                scale = min(max_width / w, max_height / h, 1.0)
                final_w = w * scale
                final_h = h * scale
                return RLImage(str(img_path), width=final_w, height=final_h)
        except Exception:
            return None

