def format_currency(val: Any) -> str:
    """Format currency values cleanly."""
    if not val:
        return "₹0"
    s = str(val).strip()
    if s.startswith("₹") or s.startswith("Rs"):
        return s
    try:
        f = float(re.sub(r"[^\d.]", "", s))
        return f"₹{f:,.0f}"
    except (ValueError, TypeError):
        return f"₹{s}"

def add_header_footer(canvas, doc):
    """Draw professional running header and footer on each page."""
    canvas.saveState()
    # Top decorative bar
    canvas.setFillColor(colors.HexColor("#0F294A"))
    canvas.rect(0, letter[1] - 8, letter[0], 8, fill=1, stroke=0)
    
    # Bottom running rule and text
    canvas.setStrokeColor(colors.HexColor("#CBD5E1"))
    canvas.setLineWidth(0.6)
    canvas.line(40, 36, letter[0] - 40, 36)
    
    canvas.setFont("Helvetica-Bold", 7.5)
    canvas.setFillColor(colors.HexColor("#0F294A"))
    canvas.drawString(40, 24, "WAYZO")
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(colors.HexColor("#64748B"))
    canvas.drawString(78, 24, "— AI-Powered Road Infrastructure Monitoring System")
    
    page_str = f"Page {canvas.getPageNumber()}"
    canvas.drawRightString(letter[0] - 40, 24, page_str)
    canvas.restoreState()

